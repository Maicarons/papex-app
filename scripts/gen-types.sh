#!/usr/bin/env bash
#
# gen-types.sh — Fetch the Papex server OpenAPI document and generate TypeScript
# types into src/lib/types. API types are NEVER hand-written; this script is the
# single source of truth. Run via `npm run gen:types`.
#
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT_DIR="${ROOT_DIR}/src/lib/types"
OPENAPI_URL="${PAPEX_OPENAPI_URL:-https://api.papex.example.com/openapi.json}"
GENERATED="${OUT_DIR}/papex.ts"

mkdir -p "${OUT_DIR}"

echo "Fetching OpenAPI document from ${OPENAPI_URL}"
curl -fsSL "${OPENAPI_URL}" -o "${OUT_DIR}/openapi.json"

echo "Generating types with openapi-typescript..."
npx --yes openapi-typescript@^7 "${OUT_DIR}/openapi.json" \
  --output "${GENERATED}" \
  --additional-properties \
  --alphabetize

cat > "${OUT_DIR}/index.ts" <<'EOF'
// AUTO-GENERATED by scripts/gen-types.sh — DO NOT EDIT.
// Re-run `npm run gen:types` to regenerate from the live Papex openapi.json.
export * from './papex';
EOF

echo "Types written to ${GENERATED}"
